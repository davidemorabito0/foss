#!/usr/bin/perl
# Carica su GitHub (ramo $RAMO, di serie main) il contenuto di una cartella come un commit, senza git
# (serve solo «gh», già collegato all'account). Si usa quando sul computer git non c'è.
# Uso: perl sviluppo/strumenti/pubblica.pl <cartella del progetto> <ambito ("" = tutto)> <messaggio> [--prova]
#   --prova: dice solo cosa cambierebbe.   RAMO=prova-x perl ... : pubblica su un ramo di prova (lo crea da main).
use strict; use warnings;
use JSON::PP; use Digest::SHA qw(sha1_hex); use File::Find; use MIME::Base64; use File::Temp qw(tempdir);
my ($radice, $ambito, $msg, $prova) = @ARGV;
die "uso: pubblica.pl <cartella> <ambito> <messaggio> [--prova]\n" unless defined $msg;
my $REPO = 'davidemorabito0/foss'; my $GH = "$ENV{HOME}/.local/bin/gh"; $GH = 'gh' unless -x $GH;
my $J = JSON::PP->new->utf8->canonical;
my $tmp = tempdir(CLEANUP => 1);
sub gh { my ($metodo, $percorso, $corpo) = @_;
  my $cmd = "$GH api -X $metodo repos/$REPO/$percorso";
  if (defined $corpo) { open my $h, '>', "$tmp/corpo.json" or die; print $h $J->encode($corpo); close $h; $cmd .= " --input $tmp/corpo.json"; }
  my $out = `$cmd`; die "errore GitHub su $percorso:\n$out" if $?; return $J->decode($out); }
my @VIA = (qr{^privato/}, qr{^\.git/}, qr{^desktop/src-tauri/target/}, qr{^desktop/src-tauri/gen/}, qr{^desktop/src-tauri/permissions/autogenerated/},
           qr{(^|/)node_modules/}, qr{(^|/)__pycache__/}, qr{(^|/)\.DS_Store$}, qr{(^|/)Thumbs\.db$}, qr{^sviluppo/test/app/shot/},
           qr{^android/\.gradle/}, qr{^android/(app/)?build/}, qr{^android/app/src/main/res/(mipmap-[a-z]+dpi|drawable-[a-z]+dpi)/}, qr{^android/app/src/main/res/values/colori_icona\.xml$});
my %locale;
find({ no_chdir => 1, wanted => sub { return unless -f $_ && ! -l $_; (my $p = $_) =~ s{^\Q$radice\E/}{};
  return if grep { $p =~ $_ } @VIA; return unless $p =~ /^\Q$ambito\E/;
  open my $h, '<:raw', $_ or die; local $/; my $c = <$h>; close $h;
  $locale{$p} = { sha => sha1_hex("blob " . length($c) . "\0" . $c), file => $_, x => (-x $_ ? 1 : 0) }; }}, $radice);
my $RAMO = $ENV{RAMO} || 'main';
my $ref = eval { gh('GET', "git/ref/heads/$RAMO") };
if (!$ref) { my $m = gh('GET', 'git/ref/heads/main'); gh('POST', 'git/refs', { ref => "refs/heads/$RAMO", sha => $m->{object}{sha} }); $ref = gh('GET', "git/ref/heads/$RAMO"); print "creato il ramo $RAMO\n"; }
my $testa = $ref->{object}{sha}; my $commit = gh('GET', "git/commits/$testa");
my $albero = gh('GET', "git/trees/$commit->{tree}{sha}?recursive=1"); die "albero troncato" if $albero->{truncated};
my %remoto = map { $_->{path} => $_ } grep { $_->{type} eq 'blob' && $_->{path} =~ /^\Q$ambito\E/ } @{$albero->{tree}};
my (@voci, @n, @c, @t);
for my $p (sort keys %locale) { my $r = $remoto{$p}; next if $r && $r->{sha} eq $locale{$p}{sha};
  if ($r) { push @c, $p } else { push @n, $p }
  push @voci, { path => $p, mode => ($r ? $r->{mode} : '100644'), file => $locale{$p}{file}, sha => $locale{$p}{sha} }; }
for my $p (sort keys %remoto) { next if $locale{$p}; push @t, $p; push @voci, { path => $p, mode => $remoto{$p}{mode}, sha => undef }; }
printf "$RAMO: %s\nnuovi %d, cambiati %d, tolti %d\n", substr($testa,0,7), scalar @n, scalar @c, scalar @t;
print "  + $_\n" for @n; print "  ~ $_\n" for @c; print "  - $_\n" for @t;
exit 0 if $prova || !@voci;
for my $v (@voci) { next unless $v->{file}; open my $h, '<:raw', $v->{file} or die; local $/; my $c = <$h>; close $h;
  my $b = gh('POST', 'git/blobs', { content => encode_base64($c, ''), encoding => 'base64' }); die "sha diverso per $v->{path}" unless $b->{sha} eq $v->{sha}; delete $v->{file}; }
my $na = gh('POST', 'git/trees', { base_tree => $commit->{tree}{sha}, tree => [ map { { path => $_->{path}, mode => $_->{mode}, type => 'blob', sha => $_->{sha} } } @voci ] });
my $nc = gh('POST', 'git/commits', { message => $msg, tree => $na->{sha}, parents => [$testa], author => { name => $commit->{author}{name}, email => $commit->{author}{email} } });   # stesso autore del commit precedente
gh('PATCH', "git/refs/heads/$RAMO", { sha => $nc->{sha}, force => JSON::PP::false }); print "pubblicato: $nc->{sha}\n";
