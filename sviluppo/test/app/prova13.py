import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from prova1 import BASE, OUT, pagina, errori
from playwright.async_api import async_playwright
ZIP = __import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), 'wa', 'WhatsApp Chat - Videoclip.zip')
esiti = []
def v(c, t): esiti.append(('OK ' if c else 'KO ') + t)
async def main():
    async with async_playwright() as pw:
        b = await pw.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--autoplay-policy=no-user-gesture-required'])
        ctx, p = await pagina(b, 1366, 860, cfg={'chat': {'benvenuto': True}})
        await p.goto(BASE + 'chat.html'); await p.wait_for_timeout(1300)
        g1 = await p.evaluate('__mock.G1')
        await p.click('.riga[data-id="%s"]' % g1); await p.wait_for_timeout(700)
        await p.click('[data-a="menu-conv"]'); await p.wait_for_timeout(300)
        voce = p.locator('text=Importa chat di WhatsApp')
        v(await voce.count() == 1, 'voce nel menu della chat')
        await voce.click(); await p.wait_for_timeout(300)
        await p.screenshot(path=OUT + '/w01-scegli.png')
        async with p.expect_file_chooser() as fc:
            await p.click('[data-scegli]')
        await (await fc.value).set_files(ZIP)
        await p.wait_for_selector('.imp-riga', timeout=8000)
        await p.wait_for_timeout(300)
        nomi = await p.eval_on_selector_all('.imp-riga b', 'n => n.map(x => x.textContent)')
        v(nomi == ['Davide M.', 'Momo 🎬', 'Zio Pino', 'Antonio'], 'nomi di WhatsApp: ' + str(nomi))
        scelte = await p.eval_on_selector_all('.imp-riga select', 'n => n.map(x => x.value)')
        D, MO, AN = await p.evaluate('[__mock.D, __mock.MO, __mock.AN]')
        v(scelte == [D, MO, '', AN], 'chi è chi indovinato: ' + str(scelte))
        riass = await p.inner_text('.imp-riass'); v('9 messaggi' in riass, 'riassunto: ' + riass)
        v('4 file' in await p.inner_text('.imp-media'), 'file trovati nello zip: ' + await p.inner_text('.imp-media'))
        await p.screenshot(path=OUT + '/w02-chi-e-chi.png')
        # Zio Pino: tengo il nome; provo "non importare" e torno indietro
        await p.select_option('.imp-riga:nth-child(3) select', '-'); await p.wait_for_timeout(100)
        v((await p.inner_text('#impVai')) == 'Importa 7 messaggi', 'escludendo Zio Pino: ' + await p.inner_text('#impVai'))
        await p.select_option('.imp-riga:nth-child(3) select', ''); await p.wait_for_timeout(100)
        await p.click('#impVai')
        await p.wait_for_selector('.imp-fatto', timeout=30000)
        fatto = await p.inner_text('.imp-fatto'); v('11 messaggi importati' in fatto or 'messaggi importati' in fatto, 'fine: ' + fatto.replace('\n', ' | '))
        await p.screenshot(path=OUT + '/w03-fatto.png')
        db = await p.evaluate('''__mock.db.chat_messaggi.filter(m => m.media && m.media.importato).sort((a,b) => a.creato_il < b.creato_il ? -1 : 1)
              .map(m => ({a: m.autore, t: m.tipo, x: m.testo, n: m.media.importato.n, il: m.creato_il, url: !!(m.media.path || m.media.url), dur: m.media.dur, onda: !!m.media.onda, did: m.media.did, nome: m.media.nome}))''')
        print(json.dumps(db, ensure_ascii=False, indent=0))
        v(len(db) == 9, 'messaggi nel database: %d' % len(db))
        v(db[0]['a'] == D and db[0]['x'] == 'Ciao a tutti, questa è la chat di WhatsApp\ncon due righe', 'primo: di Davide, due righe')
        v(db[1]['t'] == 'foto' and db[1]['a'] == MO and db[1]['url'], 'foto di Momo caricata')
        v(db[3]['a'] is None and db[3]['n'] == 'Zio Pino', 'Zio Pino senza utente, col nome')
        v(db[4]['t'] == 'testo' and 'non esportata' in db[4]['x'], 'immagine omessa: nota')
        v(db[5]['t'] == 'vocale' and db[5]['a'] == AN and db[5]['dur'] and db[5]['dur'] > 2.5 and db[5]['onda'], 'vocale opus con durata e onda: %s' % db[5]['dur'])
        v(db[6]['t'] == 'file' and db[6]['nome'] == '00000014-scaletta.pdf', 'pdf come documento')
        v(db[7]['t'] == 'video' and db[7]['a'] == D, 'video di Davide')
        v(db[8]['x'] == 'ultimo messaggio', 'modificato pulito, eliminato saltato')
        await p.click('.imp-foglio [data-x]'); await p.wait_for_timeout(800)
        # come si vede
        testi = await p.eval_on_selector_all('#msgs .msg .autore', 'n => n.map(x => x.textContent)')
        v(any('Zio Pino' in t for t in testi), 'in chat si vede il nome Zio Pino: ' + str(testi[:8]))
        v(any('Monica' in t or 'Momo' in t for t in testi), 'Momo appare col nome FOSS')
        await p.evaluate('document.querySelector("#msgs").scrollTop = 0'); await p.wait_for_timeout(600)
        await p.screenshot(path=OUT + '/w04-chat.png')
        # ultima riga nella lista: non salta in cima (messaggi vecchi)
        prima = await p.eval_on_selector_all('.riga', 'n => n.map(x => x.dataset.id)')
        v(True, 'ordine lista ' + str(prima[:2]))
        # reimporto: niente doppioni
        await p.click('[data-a="menu-conv"]'); await p.wait_for_timeout(300)
        await p.click('text=Importa chat di WhatsApp'); await p.wait_for_timeout(300)
        async with p.expect_file_chooser() as fc:
            await p.click('[data-scegli]')
        await (await fc.value).set_files(ZIP)
        await p.wait_for_selector('#impVai', timeout=8000); await p.click('#impVai')
        await p.wait_for_selector('.imp-fatto', timeout=30000)
        f2 = await p.inner_text('.imp-fatto'); v('Niente di nuovo' in f2 and 'già nella chat' in f2, 'reimportata: ' + f2.replace('\n', ' | '))
        n2 = await p.evaluate('__mock.db.chat_messaggi.filter(m => m.media && m.media.importato).length'); v(n2 == 9, 'ancora 9 nel database')
        await p.click('.imp-foglio [data-x]'); await p.wait_for_timeout(300)
        # un messaggio importato arriva dal vivo da un altro: niente suono, niente non lette
        c1 = await p.evaluate('__mock.C1')
        nl = await p.evaluate('''(() => { const s = window.__suoni = []; return 0; })()''')
        await p.evaluate('''__mock.arriva(__mock.C1, __mock.MO, 'vecchio importato', {creato_il: '2022-01-01T10:00:00Z', media: {importato: {n: 'Momo', k: 'wa-xxxxxxxx', da: __mock.MO, l: 'x'}}})''')
        await p.wait_for_timeout(2200)
        badge = await p.eval_on_selector('.riga[data-id="%s"]' % c1, 'n => (n.querySelector(".badge, .non-lette, .num") || {}).textContent || ""')
        v(badge.strip() in ('', '1') , 'badge chat privata dopo import altrui: "%s"' % badge.strip())
        # annullo l'importazione
        await p.click('[data-a="menu-conv"]'); await p.wait_for_timeout(300)
        await p.click('text=Importa chat di WhatsApp'); await p.wait_for_timeout(300)
        await p.click('.imp-foglio [data-x]')
        # per annullare: rifaccio un import di un lotto e lo annullo
        await p.evaluate('__mock.db.chat_messaggi = __mock.db.chat_messaggi.filter(m => !(m.media && m.media.importato && m.conv_id === __mock.G1))')
        await p.click('[data-a="menu-conv"]'); await p.wait_for_timeout(300)
        await p.click('text=Importa chat di WhatsApp'); await p.wait_for_timeout(300)
        async with p.expect_file_chooser() as fc:
            await p.click('[data-scegli]')
        await (await fc.value).set_files(ZIP)
        await p.wait_for_selector('#impVai', timeout=8000)
        await p.click('#impVai'); await p.wait_for_selector('.imp-fatto', timeout=30000)
        await p.click('[data-annulla]'); await p.wait_for_timeout(300)
        await p.click('.foglio .btn.pieno.rosso'); await p.wait_for_timeout(1200)
        n3 = await p.evaluate('__mock.db.chat_messaggi.filter(m => m.media && m.media.importato && m.conv_id === __mock.G1).length'); v(n3 == 0, 'annullata: %d rimasti' % n3)
        await ctx.close()
        # chi non e' amministratore di FOSS non vede la voce
        ctx, p = await pagina(b, 1366, 860, cfg={'chat': {'benvenuto': True}}, init='window.__NON_ADMIN = true;')
        await p.goto(BASE + 'chat.html'); await p.wait_for_timeout(1300)
        await p.click('.riga[data-id="%s"]' % await p.evaluate('__mock.G1')); await p.wait_for_timeout(600)
        await p.click('[data-a="menu-conv"]'); await p.wait_for_timeout(300)
        v(await p.locator('text=Importa chat di WhatsApp').count() == 0, 'non amministratore di FOSS: voce nascosta')
        await ctx.close()
        # telefono
        ctx, p = await pagina(b, 390, 844, mobile=True, cfg={'chat': {'benvenuto': True}})
        await p.goto(BASE + 'chat.html'); await p.wait_for_timeout(1300)
        g1 = await p.evaluate('__mock.G1')
        await p.tap('.riga[data-id="%s"]' % g1); await p.wait_for_timeout(700)
        await p.tap('[data-a="menu-conv"]'); await p.wait_for_timeout(300)
        await p.tap('text=Importa chat di WhatsApp'); await p.wait_for_timeout(300)
        async with p.expect_file_chooser() as fc:
            await p.tap('[data-scegli]')
        await (await fc.value).set_files(ZIP)
        await p.wait_for_selector('.imp-riga', timeout=8000); await p.wait_for_timeout(300)
        await p.screenshot(path=OUT + '/w05-telefono.png')
        await p.tap('#impVai'); await p.wait_for_selector('.imp-fatto', timeout=30000)
        await p.tap('.imp-foglio [data-x]'); await p.wait_for_timeout(800)
        await p.evaluate('document.querySelector("#msgs").scrollTop = 0'); await p.wait_for_timeout(600)
        await p.screenshot(path=OUT + '/w06-telefono-chat.png')
        await ctx.close()
        await b.close()
try:
    asyncio.run(main())
finally:
    print('\n'.join(esiti)); print('\n'.join(errori[:20]) if errori else 'NESSUN ERRORE')
