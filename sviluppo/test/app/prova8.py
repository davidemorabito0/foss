import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from prova1 import pagina, BASE, OUT, errori
from playwright.async_api import async_playwright

def ok(cond, cosa):
    print(('  ok  ' if cond else '  XX  ') + cosa)
    if not cond: errori.append('PROVA FALLITA: ' + cosa)

async def tieni(p, sel):
    box = await p.locator(sel).bounding_box()
    cx, cy = box['x'] + box['width'] / 2, box['y'] + min(box['height'] / 2, 30)
    await p.evaluate("""([x,y])=>{const t=document.elementFromPoint(x,y); const o={identifier:1,target:t,clientX:x,clientY:y}; t.dispatchEvent(new TouchEvent('touchstart',{bubbles:true,touches:[new Touch(o)],changedTouches:[new Touch(o)]}));}""", [cx, cy])
    await p.wait_for_timeout(650)
    await p.evaluate("""([x,y])=>{const t=document.elementFromPoint(x,y); const o={identifier:1,target:t,clientX:x,clientY:y}; t.dispatchEvent(new TouchEvent('touchend',{bubbles:true,cancelable:true,touches:[],changedTouches:[new Touch(o)]}));}""", [cx, cy])
    await p.wait_for_timeout(450)

